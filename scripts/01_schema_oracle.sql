-- =====================================================================
-- TB_TUTOR
-- =====================================================================
CREATE TABLE TB_TUTOR (
    ID_TUTOR                NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_TUTOR                VARCHAR2(120)   NOT NULL,
    NR_CPF                  VARCHAR2(14)    NOT NULL,
    DS_EMAIL                VARCHAR2(150)   NOT NULL,
    NR_TELEFONE             VARCHAR2(20)    NOT NULL,
    DS_ENDERECO             VARCHAR2(200),
    NM_CIDADE               VARCHAR2(60),
    SG_UF                   VARCHAR2(2),
    DT_CADASTRO             TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    FL_ACEITA_NOTIFICACOES  NUMBER(1)       DEFAULT 1 NOT NULL,
    CONSTRAINT UK_TUTOR_CPF UNIQUE (NR_CPF)
);

-- =====================================================================
-- TB_VETERINARIO
-- =====================================================================
CREATE TABLE TB_VETERINARIO (
    ID_VETERINARIO   NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_VETERINARIO   VARCHAR2(120)  NOT NULL,
    NR_CRMV          VARCHAR2(20)   NOT NULL,
    DS_ESPECIALIDADE VARCHAR2(80),
    DS_EMAIL         VARCHAR2(150)  NOT NULL,
    NR_TELEFONE      VARCHAR2(20),
    FL_ATIVO         NUMBER(1)      DEFAULT 1 NOT NULL,
    DT_CADASTRO      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_VET_CRMV UNIQUE (NR_CRMV)
);

-- =====================================================================
-- TB_PET
-- =====================================================================
CREATE TABLE TB_PET (
    ID_PET          NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_PET          VARCHAR2(80)    NOT NULL,
    DS_RACA         VARCHAR2(80)    NOT NULL,
    DT_NASCIMENTO   DATE            NOT NULL,
    TP_SEXO         NUMBER(1)       NOT NULL,
    VL_PESO_KG      NUMBER(5,2)     NOT NULL,
    TP_PORTE        NUMBER(1)       NOT NULL,
    NR_MICROCHIP    VARCHAR2(20),
    FL_CASTRADO     NUMBER(1)       DEFAULT 0 NOT NULL,
    DS_OBSERVACOES  VARCHAR2(500),
    DT_CADASTRO     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    ID_TUTOR        NUMBER(10)      NOT NULL,
    CONSTRAINT FK_PET_TUTOR FOREIGN KEY (ID_TUTOR) REFERENCES TB_TUTOR(ID_TUTOR)
);

CREATE UNIQUE INDEX UX_PET_MICROCHIP ON TB_PET(NR_MICROCHIP);

-- =====================================================================
-- TB_CONSULTA
-- =====================================================================
CREATE TABLE TB_CONSULTA (
    ID_CONSULTA         NUMBER(10)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DT_HR_CONSULTA      TIMESTAMP       NOT NULL,
    TP_CONSULTA         NUMBER(2)       NOT NULL,
    ST_CONSULTA         NUMBER(2)       DEFAULT 1 NOT NULL,
    DS_MOTIVO           VARCHAR2(1000),
    DS_DIAGNOSTICO      VARCHAR2(2000),
    DS_PRESCRICAO       VARCHAR2(2000),
    DS_OBSERVACOES      VARCHAR2(2000),
    DT_PROXIMO_RETORNO  DATE,
    VL_COBRADO          NUMBER(10,2),
    DT_CRIACAO          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    ID_PET              NUMBER(10)      NOT NULL,
    ID_VETERINARIO      NUMBER(10)      NOT NULL,
    CONSTRAINT FK_CONSULTA_PET FOREIGN KEY (ID_PET) REFERENCES TB_PET(ID_PET),
    CONSTRAINT FK_CONSULTA_VET FOREIGN KEY (ID_VETERINARIO) REFERENCES TB_VETERINARIO(ID_VETERINARIO)
);

CREATE INDEX IX_CONSULTA_DATA ON TB_CONSULTA(DT_HR_CONSULTA);
CREATE INDEX IX_CONSULTA_PET_DATA ON TB_CONSULTA(ID_PET, DT_HR_CONSULTA);

-- =====================================================================
-- TB_VACINA
-- =====================================================================
CREATE TABLE TB_VACINA (
    ID_VACINA        NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_VACINA        VARCHAR2(80)   NOT NULL,
    DT_APLICACAO     DATE           NOT NULL,
    DT_PROXIMA_DOSE  DATE,
    NR_LOTE          VARCHAR2(50),
    NM_FABRICANTE    VARCHAR2(80),
    DS_OBSERVACOES   VARCHAR2(500),
    DT_REGISTRO      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ID_PET           NUMBER(10)     NOT NULL,
    ID_VETERINARIO   NUMBER(10),
    CONSTRAINT FK_VACINA_PET FOREIGN KEY (ID_PET) REFERENCES TB_PET(ID_PET),
    CONSTRAINT FK_VACINA_VET FOREIGN KEY (ID_VETERINARIO) REFERENCES TB_VETERINARIO(ID_VETERINARIO)
);

CREATE INDEX IX_VACINA_PET_DATA ON TB_VACINA(ID_PET, DT_APLICACAO);

